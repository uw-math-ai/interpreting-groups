"""Search for a group form whose minimal-cost faithful carriers differ between
the two candidate cost models (theory notes, Section 3).

Cost models, in real-form-aware units (what a real-valued encoder pays):
    cost_lin  = sum over summands of the minimal real embedding dimension
                (d for real type, 2d for complex or quaternionic type);
    cost_quad = sum over summands of the realified matrix-coefficient count
                (d^2 real, 2 d^2 complex, d^2 quaternionic -- the conjugate
                pair of a quaternionic irrep is equivalent, of a complex one
                is not but spans the same real function space, cf. core.su3).

Catalog: low irreps of SU(2), SU(3), SU(4), Sp(2) = Spin(5), Spin(7), G2 with
central characters, plus all two-factor products with cyclic amalgamations of
their centers. A carrier (multiset of irreps, here subsets of size <= 3) is
faithful on (G1 x G2)/<z> iff (i) every simple factor receives a summand that
is nontrivial on it, and (ii) the joint central characters separate the
remaining center (equivalently: the subgroup of the center on which all
summands are trivial equals the quotiented subgroup).

Output: for each group form, the argmin carriers under both costs; flags any
disagreement. Exhaustive over the catalog, so a null result certifies that the
two cost models are indistinguishable on these natural families.
"""
import itertools

import numpy as np

# (name, center order n [cyclic], irreps as (label, dim, central char k in Z_n,
#  type in {R, C, H}); for Spin(4k) with Z2 x Z2 use the two-factor product
#  encoding below instead.
SIMPLE = {
    "SU2": (2, [("j1/2", 2, 1, "H"), ("j1", 3, 0, "R"), ("j3/2", 4, 1, "H"),
                ("j2", 5, 0, "R"), ("j5/2", 6, 1, "H"), ("j3", 7, 0, "R")]),
    "SU3": (3, [("3", 3, 1, "C"), ("6", 6, 2, "C"), ("8", 8, 0, "R"),
                ("10", 10, 0, "C"), ("15", 15, 1, "C")]),
    "SU4": (4, [("4", 4, 1, "C"), ("6", 6, 2, "R"), ("10", 10, 2, "C"),
                ("15", 15, 0, "R"), ("20p", 20, 0, "R"), ("20", 20, 2, "C"),
                ("20pp", 20, 3, "C"), ("36", 36, 1, "C")]),
    "Sp2": (2, [("4", 4, 1, "H"), ("5", 5, 0, "R"), ("10", 10, 0, "R"),
                ("14", 14, 0, "R"), ("16", 16, 1, "H")]),
    "Spin7": (2, [("7", 7, 0, "R"), ("8", 8, 1, "R"), ("21", 21, 0, "R"),
                  ("48", 48, 1, "R")]),
    "G2": (1, [("7", 7, 0, "R"), ("14", 14, 0, "R")]),
}


def cost_lin(dim, typ):
    return dim if typ == "R" else 2 * dim


def cost_quad(dim, typ):
    return dim * dim if typ in ("R", "H") else 2 * dim * dim


def group_forms():
    """Yield (name, center elements as tuples, irreps with vector-valued
    characters, quotient subgroups)."""
    # single simple groups and their central quotients
    for name, (n, irreps) in SIMPLE.items():
        center = [(k,) for k in range(n)]
        reps = [(lab, d, (k,), t, (True,)) for lab, d, k, t in irreps]
        for m in _subgroups_cyclic(n):
            yield f"{name}/Z{len(m)}" if len(m) > 1 else name, center, reps, m, (n,)
    # two-factor products with cyclic amalgamations
    for (na, (za, ia)), (nb, (zb, ib)) in itertools.combinations_with_replacement(
            sorted(SIMPLE.items()), 2):
        center = [(p, q) for p in range(za) for q in range(zb)]
        reps = []
        for la, da, ka, ta in [("triv", 1, 0, "R")] + ia:
            for lb, db, kb, tb in [("triv", 1, 0, "R")] + ib:
                if da == 1 and db == 1:
                    continue
                typ = "C" if "C" in (ta, tb) else (
                    "H" if (ta, tb).count("H") == 1 else
                    ("R" if ta == tb == "R" or ta == tb == "H" else "R"))
                nontriv = (da > 1, db > 1)
                reps.append((f"{la}x{lb}", da * db, (ka, kb), typ, nontriv))
        # quotient subgroups: cyclic groups generated by any central element
        gens = {tuple(sorted({tuple((i * p % za, i * q % zb))
                              for i in range(za * zb)}))
                for p in range(za) for q in range(zb)}
        gens.add(tuple(sorted(set(center))))      # the full (non-cyclic) center
        for sub in gens:
            yield (f"({na}x{nb})/Z{len(sub)}" if len(sub) > 1 else f"{na}x{nb}",
                   center, reps, list(sub), (za, zb))


def _subgroups_cyclic(n):
    subs = []
    for d in range(1, n + 1):
        if n % d == 0:
            subs.append([(k,) for k in range(0, n, n // d)])
    return subs


def _acts_trivially(chars, z, mods):
    """Central phases multiply across factors: trivial iff
    sum_i z_i k_i / m_i is an integer."""
    import math
    L = math.lcm(*mods)
    return sum(zi * ki * (L // m) for zi, ki, m in zip(z, chars, mods)) % L == 0


def char_kernel(carrier, center, mods):
    """Central elements on which every summand acts trivially."""
    return [z for z in center
            if all(_acts_trivially(chars, z, mods)
                   for _, _, chars, _, _ in carrier)]


def is_faithful(carrier, center, quotient, mods, n_factors):
    # every factor gets a nontrivial summand
    for f in range(n_factors):
        if not any(nt[f] for _, _, _, _, nt in carrier):
            return False
    # descend: trivial on the quotient subgroup
    for z in quotient:
        for _, _, chars, _, _ in carrier:
            if not _acts_trivially(chars, z, mods):
                return False
    # faithful on G/quotient: kernel == quotient subgroup
    return len(char_kernel(carrier, center, mods)) == len(quotient)


def main():
    disagreements = []
    for name, center, reps, quotient, mods in group_forms():
        n_factors = len(mods)
        best = {"lin": (np.inf, None), "quad": (np.inf, None)}
        for r in range(1, 4):
            for carrier in itertools.combinations(reps, r):
                if not is_faithful(carrier, center, quotient, mods, n_factors):
                    continue
                cl = sum(cost_lin(d, t) for _, d, _, t, _ in carrier)
                cq = sum(cost_quad(d, t) for _, d, _, t, _ in carrier)
                if cl < best["lin"][0]:
                    best["lin"] = (cl, carrier)
                if cq < best["quad"][0]:
                    best["quad"] = (cq, carrier)
        if best["lin"][1] is None:
            continue
        lab = lambda c: "+".join(x[0] for x in c)
        if set(x[0] for x in best["lin"][1]) != set(x[0] for x in best["quad"][1]):
            disagreements.append((name, lab(best["lin"][1]), best["lin"][0],
                                  lab(best["quad"][1]), best["quad"][0]))
            print(f"DISAGREE {name}: lin -> {lab(best['lin'][1])} "
                  f"({best['lin'][0]}), quad -> {lab(best['quad'][1])} "
                  f"({best['quad'][0]})")
    print(f"\n{len(disagreements)} disagreement(s) found over the catalog.")
    if not disagreements:
        print("Null result: on all catalogued group forms the two cost models "
              "select the same minimal faithful carrier.")


if __name__ == "__main__":
    main()
